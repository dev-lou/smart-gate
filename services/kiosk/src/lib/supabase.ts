"use client";

/**
 * Supabase Sync Module
 * =====================
 * Handles syncing data between the tablet's IndexedDB and Supabase cloud.
 * The kiosk downloads enrolled students and settings, and uploads access logs.
 *
 * Offline-First Design:
 *   - All writes go to IndexedDB first (instant, always works)
 *   - Background sync pushes logs to Supabase when online
 *   - Students + settings downloaded from Supabase and cached locally
 *   - No data is ever lost — logs persist until explicitly marked synced
 *
 * 🛡️ Crash-Safe Sync:
 *   - `syncInProgress` has a timeout (30s) to prevent deadlocks
 *   - Failed upload batches are retried with exponential backoff (3 attempts)
 *   - Each log has an idempotency key (sync_id) to prevent duplicates
 *   - Auth errors stop the sync; network errors retry
 */

import { createClient, type SupabaseClient } from "@supabase/supabase-js";
import {
  storeStudents,
  getUnsyncedLogs,
  markLogsSynced,
  storeSettings,
  clearStudents,
  getAllStudents,
  type StoredStudent,
  type StoredLog,
} from "./db";

// ─── Types ──────────────────────────────────────────────────

export interface SyncStatus {
  lastSync: string | null;
  syncing: boolean;
  error: string | null;
  studentsDownloaded: number;
  logsUploaded: number;
}

// ─── State ──────────────────────────────────────────────────

let supabase: SupabaseClient | null = null;
let syncInProgress = false;
let syncTimer: ReturnType<typeof setTimeout> | null = null;

// ─── Constants ──────────────────────────────────────────────

const SYNC_TIMEOUT_MS = 30_000; // 🛡️ Max sync duration (prevents deadlock)
const BATCH_SIZE = 50; // Logs per batch
const MAX_RETRIES = 3; // Retry attempts per batch
const RETRY_BASE_DELAY = 1000; // 1s, then 2s, then 4s

// ─── Sync Lock (Crash-Safe) ─────────────────────────────────

/**
 * Acquire the sync lock with timeout.
 * Returns false if already locked.
 */
function acquireSyncLock(): boolean {
  if (syncInProgress) return false;
  syncInProgress = true;

  // 🛡️ Auto-release after timeout (prevents deadlock if crash before finally)
  syncTimer = setTimeout(() => {
    syncInProgress = false;
    console.warn("[Supabase] Sync lock timed out after 30s — force released");
  }, SYNC_TIMEOUT_MS);

  return true;
}

/**
 * Release the sync lock.
 */
function releaseSyncLock(): void {
  syncInProgress = false;
  if (syncTimer) {
    clearTimeout(syncTimer);
    syncTimer = null;
  }
}

// ─── Initialization ─────────────────────────────────────────

/**
 * Initialize the Supabase client.
 * Environment variables should be set in .env.local:
 *   NEXT_PUBLIC_SUPABASE_URL
 *   NEXT_PUBLIC_SUPABASE_ANON_KEY
 */
export function initSupabase(): boolean {
  if (supabase) return true;

  const url = process.env.NEXT_PUBLIC_SUPABASE_URL;
  const key = process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY;

  if (!url || !key) {
    console.warn("[Supabase] Missing environment variables");
    return false;
  }

  supabase = createClient(url, key);
  return true;
}

/**
 * Get the initialized Supabase client (for heartbeat uploads).
 * Returns null if not initialized.
 */
export function getSupabaseClient(): SupabaseClient | null {
  return supabase;
}

/**
 * Check if Supabase is configured and reachable.
 */
export async function checkConnection(): Promise<boolean> {
  if (!supabase) return false;

  try {
    const { error } = await supabase.from("students").select("id", { count: "exact", head: true });
    return !error;
  } catch {
    return false;
  }
}

// ─── Download Data ──────────────────────────────────────────

/**
 * Download all active students from Supabase.
 * Each student's photo is processed locally to generate the face embedding.
 *
 * 🛡️ EMBEDDING-PRESERVING MERGE (offline-first fix):
 * Previously every sync wiped ALL local embeddings and regenerated them from
 * cloud photos — so an online sync could temporarily disable face recognition
 * (and a fresh tablet offline had zero embeddings). Now:
 *   - Student unchanged since last sync (same updated_at) → keep existing
 *     embeddings. Recognition stays live across syncs, even offline.
 *   - Student new or changed → embeddings reset to [] and regenerated by
 *     processStudentPhotos() on the tablet.
 *   - Students deactivated in Supabase → dropped locally (clear below).
 */
export async function downloadStudents(): Promise<number> {
  if (!supabase) throw new Error("Supabase not initialized");

  const { data, error } = await supabase
    .from("students")
    .select("id, name, student_id, department, uniform_type, photo_url, is_active, updated_at")
    .eq("is_active", true);

  if (error) throw error;

  // Guests live in their own table (migration 011) — same face-match
  // pipeline, but uniform_type "guest" tells the kiosk to skip the
  // uniform check and grant on face match.
  // 015 E-Pass columns may not exist yet if the migration hasn't been run —
  // fall back to the legacy column set so guest sync keeps working.
  interface GuestRow {
    id: string;
    name: string;
    purpose?: string | null;
    contact?: string | null;
    host_name?: string | null;
    valid_until?: string | null;
    status?: string | null;
    photo_url: string | null;
    is_active?: boolean | null;
    updated_at: string;
  }
  let guestData: GuestRow[] | null = null;
  const guestRes = await supabase
    .from("guests")
    .select("id, name, purpose, contact, host_name, valid_until, status, photo_url, is_active, updated_at")
    .eq("is_active", true);
  if (!guestRes.error) {
    guestData = guestRes.data;
  } else if ((guestRes.error as { code?: string }).code === "42703") {
    console.warn("[Supabase] 015 not applied — syncing guests without E-Pass columns. Run database/migrations/015_epass_lockdown_policy.sql.");
    const legacy = await supabase
      .from("guests")
      .select("id, name, purpose, photo_url, is_active, updated_at")
      .eq("is_active", true);
    if (legacy.error) throw legacy.error;
    guestData = (legacy.data ?? []) as GuestRow[];
  } else {
    throw guestRes.error;
  }

  if ((!data || data.length === 0) && (!guestData || guestData.length === 0)) {
    // A successful empty result means every person is inactive or removed.
    // Clear local profiles so a deactivated person cannot be recognized offline.
    await clearStudents();
    return 0;
  }

  // Load current local students to preserve embeddings for unchanged records
  const existingStudents = await getAllStudents();
  const existingMap = new Map(existingStudents.map((s) => [s.id, s]));

  const toStored = (s: {
    id: string;
    name: string;
    student_id?: string | null;
    department?: string | null;
    uniform_type?: string | null;
    photo_url: string | null;
    is_active?: boolean | null;
    updated_at: string;
    host_name?: string | null;
    purpose?: string | null;
    valid_until?: string | null;
  }): StoredStudent => {
    const existing = existingMap.get(s.id);
    const unchanged =
      existing && existing.updated_at === s.updated_at && existing.embeddings.length > 0;

    return {
      id: s.id,
      name: s.name,
      student_id: s.student_id ?? "",
      department: s.department ?? "",
      uniform_type: s.uniform_type ?? "default",
      host_name: (s as { host_name?: string | null }).host_name ?? null,
      purpose: (s as { purpose?: string | null }).purpose ?? null,
      valid_until: (s as { valid_until?: string | null }).valid_until ?? null,
      photo_url: s.photo_url,
      // Keep computed embeddings when the record didn't change (offline-first)
      embeddings: unchanged ? existing!.embeddings : [],
      is_active: s.is_active ?? true,
      updated_at: s.updated_at,
    };
  };

  const students: StoredStudent[] = [
    ...(data ?? []).map(toStored),
    ...(guestData ?? []).map((g) =>
      toStored({
        ...g,
        student_id: "",
        department: "Guest",
        uniform_type: "guest",
      }),
    ),
  ];

  await clearStudents();
  await storeStudents(students);

  return students.length;
}

/**
 * Download system settings from Supabase.
 */
export async function downloadSettings(): Promise<void> {
  if (!supabase) throw new Error("Supabase not initialized");

  const { data, error } = await supabase.from("system_settings").select("key, value");

  if (error) throw error;
  if (!data) return;

  await storeSettings(data);
}

// ─── Upload Data ────────────────────────────────────────────

/**
 * Sleep helper for retry backoff.
 */
function sleep(ms: number): Promise<void> {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

/**
 * The exact column set the kiosk writes to `access_logs` (migration 006 schema).
 */
interface AccessLogRow {
  person_id: string | null;
  person_name: string | null;
  person_type: string | null;
  direction: string;
  method: string;
  success: boolean;
  confidence: number | null;
  failure_reason: string | null;
  gate_state: string | null;
  device_timestamp: string;
  sync_id: string;
  reason_code: string | null;
  decision_note: string | null;
  client_id: string | null;
}

/**
 * True when the error is the unique-index conflict on `sync_id`.
 * The row was already stored by an earlier attempt and only the response was
 * lost, so this is the correct end state — not a failure.
 */
function isDuplicateKeyError(error: { code?: string; message?: string } | null): boolean {
  if (!error) return false;
  return error.code === "23505" || /duplicate key value/i.test(error.message ?? "");
}

/**
 * A permission/authentication failure. Retrying or moving to the next batch can
 * never succeed, so the whole sync stops instead of burning the log queue.
 */
function isFatalAuthError(error: { code?: string; message?: string } | null): boolean {
  if (!error) return false;
  return (
    error.code === "PGRST301" ||
    error.code === "401" ||
    error.code === "403" ||
    error.code === "42501"
  );
}

/**
 * Insert rows one at a time, treating "already stored" as success.
 *
 * A batch insert is atomic: one repeated `sync_id` fails all of it with 23505.
 * This walk recovers that case without losing or double-counting anything.
 * Returns true when every row is now either newly stored or already present.
 */
function isMissingColumnError(error: { code?: string } | null): boolean {
  return !!error && error.code === "42703";
}

/**
 * Strip 015 columns so the row fits a database where the migration
 * hasn't been applied yet. The human-readable decision survives in
 * failure_reason; reason_code/decision_note/client_id apply after 015.
 */
function toLegacyRow(row: AccessLogRow): Record<string, unknown> {
  const { reason_code: _rc, decision_note: _dn, client_id: _cid, ...legacy } = row;
  void _rc;
  void _dn;
  void _cid;
  return legacy;
}

async function insertRowsIndividually(rows: AccessLogRow[]): Promise<boolean> {
  if (!supabase) return false;

  let allStored = true;
  let legacyMode = false;
  for (const row of rows) {
    const payload = legacyMode ? toLegacyRow(row) : row;
    const { error } = await supabase.from("access_logs").insert(payload as typeof row);
    if (!error || isDuplicateKeyError(error)) continue;
    if (!legacyMode && isMissingColumnError(error)) {
      console.warn("[Supabase] 015 not applied — uploading logs without reason columns. Run database/migrations/015_epass_lockdown_policy.sql.");
      legacyMode = true;
      const retry = await supabase.from("access_logs").insert(toLegacyRow(row));
      if (!retry.error || isDuplicateKeyError(retry.error)) continue;
      console.error(`[Supabase] Log ${row.sync_id} rejected:`, retry.error.message);
      allStored = false;
      continue;
    }
    console.error(`[Supabase] Log ${row.sync_id} rejected:`, error.message);
    allStored = false;
  }
  return allStored;
}

/**
 * Upload unsynchronized access logs to Supabase.
 * Uses batched inserts with retry + exponential backoff.
 * Each log includes a `sync_id` for idempotency (prevents duplicates).
 */
export async function uploadLogs(): Promise<number> {
  if (!supabase) throw new Error("Supabase not initialized");

  const unsyncedLogs = await getUnsyncedLogs();
  if (unsyncedLogs.length === 0) return 0;

  const logIds: number[] = [];
  let uploaded = 0;

  for (let i = 0; i < unsyncedLogs.length; i += BATCH_SIZE) {
    const batch = unsyncedLogs.slice(i, i + BATCH_SIZE);

    // 🛡️ Retry loop with exponential backoff
    let lastError: Error | null = null;
    let success = false;

    const rows: AccessLogRow[] = batch.map((log) => ({
      person_id: log.person_id,
      person_name: log.person_name,
      person_type: log.person_type,
      direction: log.direction,
      method: log.method,
      success: log.success,
      confidence: log.confidence,
      failure_reason: log.failure_reason,
      gate_state: log.gate_state ?? null,
      device_timestamp: log.device_timestamp,
      // Server-side idempotency key; migration 006 adds the indexed column.
      sync_id: log.sync_id,
      reason_code: (log as { reason_code?: string | null }).reason_code ?? null,
      decision_note: (log as { decision_note?: string | null }).decision_note ?? null,
      client_id: (log as { client_id?: string | null }).client_id ?? null,
    }));

    for (let attempt = 0; attempt < MAX_RETRIES; attempt++) {
      try {
        // Plain INSERT — deliberately NOT upsert().
        //
        // PostgREST compiles an upsert with `onConflict` into
        // `INSERT ... ON CONFLICT (sync_id) DO NOTHING`, and PostgreSQL needs
        // SELECT (read) rights on the table to arbitrate that conflict. The
        // kiosk authenticates anonymously and migration 006 grants the anon
        // role INSERT only, so every upsert was rejected with
        // "new row violates row-level security policy for table access_logs"
        // (HTTP 401) and the entire queue stalled forever. A plain INSERT needs
        // nothing beyond the INSERT policy. Idempotency is preserved below.
        const { error } = await supabase.from("access_logs").insert(rows);

        if (error) {
          lastError = error;

          // A batch insert is atomic, so one already-stored sync_id (a retry
          // after a lost response) fails all of it. Recover row by row.
          if (isDuplicateKeyError(error) || isMissingColumnError(error)) {
            if (await insertRowsIndividually(rows)) {
              success = true;
              break;
            }
          } else if (isFatalAuthError(error)) {
            // Auth/permission errors are fatal — stop immediately
            console.error("[Supabase] Auth error — stopping sync:", error);
            break;
          }

          // Network/server errors — retry with backoff
          if (attempt < MAX_RETRIES - 1) {
            const delay = RETRY_BASE_DELAY * Math.pow(2, attempt);
            console.warn(
              `[Supabase] Batch upload failed (attempt ${attempt + 1}/${MAX_RETRIES}), retrying in ${delay}ms:`,
              error.message,
            );
            await sleep(delay);
          }
        } else {
          success = true;
          break;
        }
      } catch (err) {
        lastError = err instanceof Error ? err : new Error(String(err));
        if (attempt < MAX_RETRIES - 1) {
          const delay = RETRY_BASE_DELAY * Math.pow(2, attempt);
          console.warn(`[Supabase] Network error, retrying in ${delay}ms:`, lastError.message);
          await sleep(delay);
        }
      }
    }

    if (!success) {
      // 🛡️ Log the error but don't crash — these logs will be retried on next sync
      console.warn(
        `[Supabase] Batch upload failed after ${MAX_RETRIES} attempts. ${batch.length} logs will retry on next sync.`,
        lastError?.message,
      );
      // Stop processing further batches (likely a systemic issue)
      break;
    }

    uploaded += batch.length;
    logIds.push(...batch.map((l) => l.id!));
  }

  // 🛡️ Mark uploaded logs as synced (atomic — only marks what actually succeeded)
  if (logIds.length > 0) {
    await markLogsSynced(logIds);
  }

  return uploaded;
}

// ─── Full Sync ──────────────────────────────────────────────

/**
 * Perform a full sync: download students + settings, upload logs.
 *
 * 🛡️ Crash-Safe:
 *   - Lock auto-releases after 30s timeout
 *   - Failed batch uploads are retried 3x with backoff
 *   - Only successfully uploaded logs are marked synced
 *   - Auth errors stop the sync; transient errors retry
 */
export async function fullSync(): Promise<SyncStatus> {
  if (!acquireSyncLock()) {
    return {
      lastSync: null,
      syncing: true,
      error: "Sync already in progress",
      studentsDownloaded: 0,
      logsUploaded: 0,
    };
  }

  try {
    if (!supabase) {
      initSupabase();
      if (!supabase) {
        return {
          lastSync: null,
          syncing: false,
          error:
            "Supabase not configured. Set NEXT_PUBLIC_SUPABASE_URL and NEXT_PUBLIC_SUPABASE_ANON_KEY",
          studentsDownloaded: 0,
          logsUploaded: 0,
        };
      }
    }

    // Check connection
    const connected = await checkConnection();
    if (!connected) {
      return {
        lastSync: null,
        syncing: false,
        error: "Cannot reach Supabase",
        studentsDownloaded: 0,
        logsUploaded: 0,
      };
    }

    // Download students and settings in parallel
    const [studentCount] = await Promise.all([downloadStudents(), downloadSettings()]);

    // Upload logs
    const logCount = await uploadLogs();

    return {
      lastSync: new Date().toISOString(),
      syncing: false,
      error: null,
      studentsDownloaded: studentCount,
      logsUploaded: logCount,
    };
  } catch (err) {
    return {
      lastSync: null,
      syncing: false,
      error: err instanceof Error ? err.message : "Unknown sync error",
      studentsDownloaded: 0,
      logsUploaded: 0,
    };
  } finally {
    releaseSyncLock();
  }
}
